    /**
     * Locate the user context when Kopere BI stores information about this user.
     *
     * @param int $userid User ID.
     * @return contextlist
     */
    public static function get_contexts_for_userid(int $userid): contextlist {
        $contextlist = new contextlist();
        $sql = "SELECT ctx.id
                  FROM {context} ctx
                 WHERE ctx.contextlevel = :contextlevel
                   AND ctx.instanceid = :userid
                   AND (
                       EXISTS (SELECT 1 FROM {local_kopere_bi_online} WHERE userid = :onlineuserid)
                       OR EXISTS (SELECT 1 FROM {local_kopere_bi_tracking} WHERE userid = :trackinguserid)
                       OR EXISTS (SELECT 1 FROM {local_kopere_bi_track_log} WHERE userid = :trackloguserid)
                       OR EXISTS (SELECT 1 FROM {local_kopere_bi_period} WHERE userid = :perioduserid)
                       OR EXISTS (SELECT 1 FROM {local_kopere_bi_engage} WHERE userid = :engageuserid)
                       OR EXISTS (SELECT 1 FROM {local_kopere_bi_log_tmp}
                                   WHERE userid = :loguserid OR relateduserid = :relateduserid)
                       OR EXISTS (SELECT 1 FROM {local_kopere_bi_page} WHERE user_id = :pageuserid)
                   )";
        $contextlist->add_from_sql($sql, [
            'contextlevel' => CONTEXT_USER,
            'userid' => $userid,
            'onlineuserid' => $userid,
            'trackinguserid' => $userid,
            'trackloguserid' => $userid,
            'perioduserid' => $userid,
            'engageuserid' => $userid,
            'loguserid' => $userid,
            'relateduserid' => $userid,
            'pageuserid' => $userid,
        ]);
        return $contextlist;
    }

    /**
     * Identify users with personal information in the requested context.
     *
     * @param userlist $userlist Users in a given context.
     */
    public static function get_users_in_context(userlist $userlist): void {
        $context = $userlist->get_context();
        if (!$context instanceof context_user) {
            return;
        }
        foreach (self::USER_TABLES as $table) {
            $sql = "SELECT userid FROM {{$table}} WHERE userid = :userid";
            $userlist->add_from_sql('userid', $sql, ['userid' => $context->instanceid]);
        }
        $userlist->add_from_sql('userid',
            'SELECT userid FROM {local_kopere_bi_log_tmp} WHERE userid = :userid',
            ['userid' => $context->instanceid]);
        $userlist->add_from_sql('relateduserid',
            'SELECT relateduserid FROM {local_kopere_bi_log_tmp} WHERE relateduserid = :userid',
            ['userid' => $context->instanceid]);
        $userlist->add_from_sql('user_id',
            'SELECT user_id FROM {local_kopere_bi_page} WHERE user_id = :userid',
            ['userid' => $context->instanceid]);
    }

    /**
     * Export Kopere BI data for the approved user and user context.
     *
     * @param approved_contextlist $contextlist Approved contexts.
     */
    public static function export_user_data(approved_contextlist $contextlist): void {
        global $DB;

        $userid = (int)$contextlist->get_user()->id;
        foreach ($contextlist->get_contexts() as $context) {
            if (!$context instanceof context_user || (int)$context->instanceid !== $userid) {
                continue;
            }
            $data = new stdClass();
            foreach (self::USER_TABLES as $table) {
                $data->{$table} = array_values($DB->get_records($table, ['userid' => $userid]));
            }
            $data->local_kopere_bi_log_tmp = array_values($DB->get_records_select('local_kopere_bi_log_tmp',
                'userid = :userid OR relateduserid = :relateduserid',
                ['userid' => $userid, 'relateduserid' => $userid]));
            $data->local_kopere_bi_page = array_values($DB->get_records('local_kopere_bi_page',
                ['user_id' => $userid]));

            $locationids = [];
            foreach ($data->local_kopere_bi_online as $record) {
                if (!empty($record->iplocationid)) {
                    $locationids[] = $record->iplocationid;
                }
            }
            $data->local_kopere_bi_iplocation = $locationids
                ? array_values($DB->get_records_list('local_kopere_bi_iplocation', 'id', array_unique($locationids)))
                : [];
            writer::with_context($context)->export_data([], $data);
        }
    }

    /**
     * Delete all personal information belonging to the user context.
     *
     * @param context $context Target context.
     */
    public static function delete_data_for_all_users_in_context(context $context): void {
        if ($context instanceof context_user) {
            self::delete_user_data((int)$context->instanceid);
        }
    }

    /**
     * Delete data for the approved user in approved contexts only.
     *
     * @param approved_contextlist $contextlist Approved contexts.
     */
    public static function delete_data_for_user(approved_contextlist $contextlist): void {
        $userid = (int)$contextlist->get_user()->id;
        foreach ($contextlist->get_contexts() as $context) {
            if ($context instanceof context_user && (int)$context->instanceid === $userid) {
                self::delete_user_data($userid);
                break;
            }
        }
    }

    /**
     * Delete data for the approved users in a user context.
     *
     * @param approved_userlist $userlist Approved users and context.
     */
    public static function delete_data_for_users(approved_userlist $userlist): void {
        $context = $userlist->get_context();
        if ($context instanceof context_user && in_array((int)$context->instanceid, $userlist->get_userids())) {
            self::delete_user_data((int)$context->instanceid);
        }
    }

    /**
     * Delete user records without removing reports or the shared IP geolocation cache.
     *
     * @param int $userid User to erase.
     */
    private static function delete_user_data(int $userid): void {
        global $DB;

        foreach (self::USER_TABLES as $table) {
            $DB->delete_records($table, ['userid' => $userid]);
        }
        $DB->delete_records_select('local_kopere_bi_log_tmp',
            'userid = :userid OR relateduserid = :relateduserid',
            ['userid' => $userid, 'relateduserid' => $userid]);
        $DB->set_field('local_kopere_bi_page', 'user_id', null, ['user_id' => $userid]);
    }
}
